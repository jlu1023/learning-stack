"""Static Review Queue for plain mode (no Obsidian, so no Dataview).

The same four views as the Dataview version in the vault template, as
Markdown tables written by `roadmap all` and `review-queue`. The file is
generated: every run replaces it.
"""
from __future__ import annotations

import datetime as dt
from collections import Counter

from .graph import CourseGraph, roadmap_courses
from .state import LEARNING_DIR, read_error_log, read_progress, read_state
from .vault import Vault, make_link

REVIEW_QUEUE_REL = f"{LEARNING_DIR}/Review Queue.md"
STUCK_DAYS = 14


def _row(cells) -> str:
    return "| " + " | ".join(str(c).replace("|", "/") for c in cells) + " |"


def _table(header: list[str], rows: list[list]) -> list[str]:
    if not rows:
        return ["Nothing here.", ""]
    return [_row(header), _row(["---"] * len(header))] + [_row(r) for r in rows] + [""]


def review_queue_text(v: Vault, today: dt.date) -> str:
    from .cli import due_items       # cli imports this module
    progress = read_progress(v)
    due = due_items(v, "mixed", today, 0)
    link = lambda rel: make_link(REVIEW_QUEUE_REL, rel)  # noqa: E731
    due_rows = [[link(i["path"]), i["course"], i["state"]["mastery"], i["state"]["review"],
                 i["state"]["last_quizzed"] or "", i["state"]["review_interval"] or ""] for i in due["due"]]
    redo_rows = [[e.get("date", ""), e.get("course", ""), e.get("node", ""), e.get("category", ""),
                  e.get("redo", "")] for e in due["redos"]]
    stuck, counts = [], Counter()
    for code in roadmap_courses(v):
        cg = CourseGraph(v, code)
        for n in cg.nodes:
            s = read_state(v, n, progress)
            counts[(code, s.mastery)] += 1
            if s.mastery == "learning" and s.mastery_since and (today - s.mastery_since).days > STUCK_DAYS:
                stuck.append([link(n), code, s.mastery_since.isoformat(),
                              s.last_quizzed.isoformat() if s.last_quizzed else ""])
    errors = sorted(read_error_log(v), key=lambda e: e.get("date", ""), reverse=True)[:10]
    error_rows = [[e.get("date", ""), e.get("course", ""), e.get("node", ""), e.get("category", ""),
                   e.get("redo", ""), e.get("redone", "")] for e in errors]
    count_rows = [[f"{c}: {m}", n] for (c, m), n in sorted(counts.items())]
    L = ["---", 'title: "Review Queue"', "type: reference", "generated: true",
         f"updated: {today.isoformat()}", "---", "", "# Review Queue", "",
         "Generated by `/learn:roadmap` (or the engine's `review-queue` command) on "
         f"{today.day} {today.strftime('%B')} {today.year}; every run replaces this file. "
         "Learner state for `human_authored: true` notes is read from `progress.md`.", "",
         "## Due for review", ""]
    L += _table(["Node", "Course", "Mastery", "Due", "Last quizzed", "Interval (days)"], due_rows)
    L += ["## Error Log redos due", ""]
    L += _table(["Date", "Course", "Node", "Category", "Redo"], redo_rows)
    L += [f"## Stuck in learning for over {STUCK_DAYS} days", ""]
    L += _table(["Node", "Course", "Learning since", "Last quizzed"], stuck)
    L += ["## Last 10 Error Log entries", ""]
    L += _table(["Date", "Course", "Node", "Category", "Redo", "Redone"], error_rows)
    L += ["## Nodes by mastery state", ""]
    L += _table(["Course and state", "Nodes"], count_rows)
    return "\n".join(L).rstrip() + "\n"

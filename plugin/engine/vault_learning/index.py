"""Generated Vault Index: `_meta/Vault Index.md`.

Folder tree to depth 3 with, for each folder, its note count (recursive), the
date its newest note was last modified, and its hub note when one exists. Notes
are named in plain text, never linked, so the index adds no graph edges (the
same rule as the Roadmaps' suggested order). Writing is idempotent: when only
the `updated:` line would change, nothing is written.
"""
from __future__ import annotations

import datetime as dt
import os
from dataclasses import dataclass, field
from pathlib import Path

from .vault import SKIP_DIRS, Vault, parse_frontmatter

INDEX_REL = "_meta/Vault Index.md"
MAX_DEPTH = 3


@dataclass
class Folder:
    rel: str                                   # posix, "" for the root
    notes: int = 0                             # recursive
    newest: float = 0.0                        # recursive, mtime
    direct: list[str] = field(default_factory=list)   # note stems directly inside
    children: dict[str, "Folder"] = field(default_factory=dict)


def _walk(root: Path) -> Folder:
    top = Folder("")
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        for fn in filenames:
            if not fn.lower().endswith(".md"):
                continue
            rel = f"{rel_dir}/{fn}" if rel_dir else fn
            if rel == INDEX_REL:
                continue
            mtime = (Path(dirpath) / fn).stat().st_mtime
            node = top
            chain = [top]
            for part in rel_dir.split("/") if rel_dir else []:
                node = node.children.setdefault(part, Folder(f"{node.rel}/{part}".lstrip("/")))
                chain.append(node)
            node.direct.append(fn[:-3])
            for f in chain:
                f.notes += 1
                f.newest = max(f.newest, mtime)
    return top


def _hub(v: Vault, f: Folder) -> str | None:
    """The folder's hub note: named after the folder, else '<name> Syllabus',
    else the only `type: moc` note directly inside it."""
    name = f.rel.rsplit("/", 1)[-1]
    for stem in (name, f"{name} Syllabus"):
        if stem in f.direct:
            return stem
    mocs = []
    for stem in f.direct:
        rel = f"{f.rel}/{stem}.md"
        fm, _, _ = parse_frontmatter(v.read_text(rel))
        if str(fm.get("type")) == "moc":
            mocs.append(stem)
    return mocs[0] if len(mocs) == 1 else None


def _date(ts: float) -> str:
    d = dt.date.fromtimestamp(ts)
    return f"{d.day} {d.strftime('%B')} {d.year}"


def render(v: Vault, today: dt.date, created: str | None) -> str:
    top = _walk(v.root)
    lines = [
        "---",
        'title: "Vault Index"',
        "type: moc",
        "generated: true",
        f"created: {created or today.isoformat()}",
        f"updated: {today.isoformat()}",
        "---",
        "",
        "# Vault Index",
        "",
        "Generated by the vault-learning engine (`index`); never hand-edit, the next run overwrites it. Folders to depth 3, each with its note count "
        "(including subfolders), when its newest note was last changed, and its hub note. Notes are "
        "named in plain text, not linked, so this index adds no graph edges. Dot-folders "
        "(`.claude`, `.obsidian` and so on) are left out.",
        "",
        f"**{top.notes:,} notes in total**, newest change {_date(top.newest)}. "
        f"{len(top.direct)} notes sit at the vault root.",
        "",
    ]

    def emit(f: Folder, depth: int) -> None:
        for name in sorted(f.children, key=str.lower):
            c = f.children[name]
            hub = _hub(v, c)
            bits = [f"{c.notes:,} note{'s' if c.notes != 1 else ''}", f"last changed {_date(c.newest)}"]
            if hub:
                bits.append(f"hub: {hub}")
            lines.append(f"{'  ' * (depth - 1)}- **{name}/**: " + "; ".join(bits))
            if depth < MAX_DEPTH:
                emit(c, depth + 1)

    emit(top, 1)
    return "\n".join(lines) + "\n"


def _strip_updated(text: str) -> str:
    return "\n".join(l for l in text.splitlines() if not l.startswith("updated:"))


def write_index(v: Vault, today: dt.date, dry_run: bool = False) -> dict:
    created = None
    old = None
    if v.exists(INDEX_REL):
        old = v.read_text(INDEX_REL)
        fm, _, _ = parse_frontmatter(old)
        created = str(fm["created"]) if fm.get("created") else None
    text = render(v, today, created)
    if old is not None and _strip_updated(old) == _strip_updated(text):
        action = "unchanged"
    else:
        action = "rewritten" if old is not None else "created"
        if not dry_run:
            v.write_text(INDEX_REL, text)
    return {"index": INDEX_REL, "action": action, "dry_run": dry_run}
